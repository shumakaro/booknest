// Реальная приемка браузера: сетевые ответы не подменяются, секреты читаются только локально.
const { createRequire } = require('node:module');
const path = require('node:path');
const fs = require('node:fs');
const { randomBytes } = require('node:crypto');
const { chromium } = createRequire(path.resolve('react-app/package.json'))('@playwright/test');
(async()=>{
 const browser=await chromium.launch({channel:process.platform==='win32'?'msedge':undefined,headless:true});
 const page=await browser.newPage();const errors=[];page.on('pageerror',e=>errors.push(e.message));
 const base='http://127.0.0.1:5173'; const checks=[];
 const accounts=JSON.parse(fs.readFileSync('.tools/demo-accounts.json','utf8'));
 try {
  await page.goto(base+'/books');
  await page.locator('.book-card').first().waitFor();
  const heading=await page.locator('.book-card h3').first().innerText();
  await page.getByLabel('Поиск по названию').fill(heading);
  await page.waitForResponse(r=>r.status()===200 && new URL(r.url()).pathname.endsWith('/books') && new URL(r.url()).searchParams.get('q')===heading);
  await page.getByRole('button',{name:'Сбросить фильтры',exact:true}).click();
  await page.waitForResponse(r=>r.status()===200 && new URL(r.url()).pathname.endsWith('/books') && !new URL(r.url()).searchParams.get('q'));
  await page.getByLabel('Жанр',{exact:true}).selectOption('cs');
  await page.waitForResponse(r=>r.status()===200 && new URL(r.url()).searchParams.get('genre')==='cs');
  await page.getByLabel('Только доступные',{exact:true}).check();
  const filtered=await (await page.waitForResponse(r=>r.status()===200 && new URL(r.url()).searchParams.get('available_only')==='true')).json();
  if(filtered.items.some(book=>book.available<1))throw Error('Availability filter mismatch');
  await page.getByLabel('Сортировка',{exact:true}).selectOption('-year');
  const sorted=await(await page.waitForResponse(r=>r.status()===200 && new URL(r.url()).searchParams.get('sort')==='-year')).json();
  if(sorted.items.some((b,i,a)=>i>0 && a[i-1].year<b.year))throw Error('Sort mismatch');
  checks.push('real search, genre, availability, sort and reset');
  await page.goto(base+'/register');
  const email='stage3-'+Date.now()+'@example.com';const password=randomBytes(16).toString('hex')+'A1';
  await page.getByLabel('E-mail',{exact:true}).fill(email);
  await page.getByLabel('Пароль',{exact:true}).fill('abcdefgh');
  await page.getByRole('button',{name:'Зарегистрироваться',exact:true}).click();
  await page.getByRole('alert').filter({hasText:'буквы и цифры'}).waitFor();
  await page.getByLabel('Пароль',{exact:true}).fill(password);
  await page.getByRole('button',{name:'Зарегистрироваться',exact:true}).click();
  await page.getByRole('status').filter({hasText:'Регистрация завершена'}).waitFor();
  await page.getByRole('link',{name:'Перейти ко входу',exact:true}).click();
  await page.getByLabel('E-mail',{exact:true}).fill(email);
  await page.getByLabel('Пароль',{exact:true}).fill(password);
  const tokenResponse=page.waitForResponse(r=>new URL(r.url()).pathname.endsWith('/auth/token'));
  await page.getByRole('button',{name:'Войти',exact:true}).click();
  const token=(await(await tokenResponse).json()).access_token;
  await page.waitForURL('**/books');
  await page.getByRole('button',{name:'Выйти',exact:true}).waitFor();
  const refresh=page.waitForResponse(r=>r.status()===200 && new URL(r.url()).pathname.endsWith('/auth/refresh'));
  await page.reload();await refresh;
  await page.getByRole('button',{name:'Выйти',exact:true}).waitFor();
  if(await page.getByRole('link',{name:'Добавить книгу',exact:true}).count())throw Error('Librarian controls shown to member');
  await page.goto(base+'/books/new');await page.getByRole('heading',{name:'Недостаточно прав',exact:true}).waitFor();
  const forbidden=await page.request.post(base+'/api/v1/books',{headers:{Authorization:'Bearer '+token},data:{}});
  if(forbidden.status()!==403)throw Error('Member POST status '+forbidden.status());
  checks.push('registration validation, real registration/login, refresh on reload, member restrictions 403');
  await page.goto(base+'/books');await page.locator('.book-card').first().waitFor();
  const card=page.locator('.book-card').first();
  const wishlistResponse=page.waitForResponse(r=>r.status()===204 && new URL(r.url()).pathname.includes('/wishlist/'));
  await card.getByRole('button',{name:'В желаемое',exact:true}).click();await wishlistResponse;
  await page.getByRole('complementary',{name:'Уведомления'}).getByText('Книга добавлена в желаемое',{exact:true}).waitFor();
  await page.getByRole('link',{name:'Желаемое',exact:true}).click();
  await page.getByRole('button',{name:'Удалить из желаемого',exact:true}).first().click();
  await page.getByRole('complementary',{name:'Уведомления'}).getByText('Книга удалена из желаемого',{exact:true}).waitFor();
  checks.push('real wishlist add and removal, success notifications');
  await page.getByRole('button',{name:'Выйти',exact:true}).click();
  await page.getByRole('link',{name:'Войти',exact:true}).waitFor();
  await page.goto(base+'/wishlist');await page.waitForURL('**/login');
  const unauthorized=await page.request.post(base+'/api/v1/books',{data:{}});
  if(unauthorized.status()!==401)throw Error('Anonymous POST status '+unauthorized.status());
  checks.push('logout, protected route redirect and anonymous 401');
  await page.keyboard.press('Tab');
  // Начальный Tab зависит от оставшегося фокуса; сама ссылка доступна через клавиатуру.
  await page.getByRole('link',{name:'Перейти к содержимому',exact:true}).focus();
  await page.keyboard.press('Enter');
  if(await page.locator('#main-content').evaluate(el=>document.activeElement!==el))throw Error('Skip link did not focus main');
  checks.push('skip link moves focus to main');
  if(errors.length)throw Error(errors.join('\n'));
  fs.writeFileSync('docs/stage3/real-ui.json',JSON.stringify({api:'real FastAPI/PostgreSQL',checks,pageErrors:errors,createdUser:email,createdRole:'member',passwordSaved:false},null,2));
  console.log('Real UI checks passed:',checks.length);
 } finally {await browser.close();}
})().catch(error=>{console.error(error);process.exitCode=1;});
