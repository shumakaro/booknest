def font(style):
    style.font.name = "Times New Roman"
    style.font.size = Pt(14)
    style.font.color.rgb = RGBColor(0, 0, 0)
    style.font.underline = False
    rpr = style.element.get_or_add_rPr()
    fonts = rpr.find(qn("w:rFonts"))
    if fonts is None:
        fonts = OxmlElement("w:rFonts")
        rpr.insert(0, fonts)
    for name in list(fonts.attrib):
        del fonts.attrib[name]
    for name in ["ascii", "hAnsi", "eastAsia", "cs"]:
        fonts.set(qn("w:" + name), "Times New Roman")
    for border in style.element.xpath(".//w:pBdr"):
        border.getparent().remove(border)


def para(doc, text="", bold=False, verbatim=False):
    if not verbatim and not text.startswith("[ЛР"):
        # Только пробелы в обычном тексте; исходные строки кода остаются точными.
        text = re.sub(r"(?<=[А-Яа-яЁё])(?=\d)", " ", text)
        text = re.sub(r"(?<=\d)(?=[А-Яа-яЁё])", " ", text)
        text = re.sub(r"\b(PR|CI|ID)(?=\d)", r"\1 ", text)
        text = re.sub(r";(?=\S)", "; ", text)
    p = doc.add_paragraph()
    p.paragraph_format.widow_control = True
    run = p.add_run(text)
    run.bold = bold
    return p


def paragraphs(doc, text):
    # Сохраняются смысловые абзацы прежнего отчета; служебные Markdown-маркеры снимаются.
    for block in re.split(r"\n\s*\n", text):
        block = block.strip()
        if not block:
            continue
        if block.startswith("### "):
            line, _, rest = block.partition("\n")
            p = para(doc, line.removeprefix("### "), True)
            p.paragraph_format.keep_with_next = True
            if rest.strip():
                para(doc, rest.strip())
        else:
            block = re.sub(r"`([^`]+)`", r"\1", block)
            para(doc, block)


