/* ==========================================================================
   api/client.js — единый клиент для всех запросов к внешнему API.

   ВАЖНО (для защиты): это ЕДИНСТВЕННОЕ место во всём проекте, где вызывается
   fetch. Никакой другой модуль (ui/, main.js) не должен обращаться к сети
   напрямую. Такое разделение даёт три пользы:

   1. Базовый URL меняется в одной строке — не надо искать по всему проекту.
   2. Обработка ошибок централизована — одинаковая для всех запросов.
   3. Легко подменить клиент в тестах или при смене API.

   Этот модуль знает про сеть, но НЕ знает про DOM. Он не трогает страницу,
   не ищет элементы, не рендерит. Его задача — вернуть данные или бросить
   понятную ошибку.
   ========================================================================== */

// Базовый адрес Open Library. Все запросы будут относительно него.
// Вынесен в константу, чтобы в одном месте менять при необходимости.
const BASE_URL = "https://openlibrary.org";

// Задержка перед повторным запросом при ошибке сервера.
const RETRY_DELAY = 500;

// Простая функция ожидания.
function wait(ms) {
  return new Promise((resolve) => {
    setTimeout(resolve, ms);
  });
}

/* ------------------------------------------------------------------
   ApiError — свой класс ошибки для всех проблем с сетью и API.

   Наследуется от встроенного Error, чтобы работали стандартные свойства
   (message, stack). Дополнительно хранит:
     status  — HTTP-код ответа (404, 500, 0 для сетевой ошибки);
     details — тело ответа от сервера, если оно было (может быть null).

   Зачем свой класс:
     - UI может различать ошибки по коду: 404 — «не найдено»,
       5xx — «ошибка сервера», status 0 — «нет соединения»;
     - в catch можно проверить `err instanceof ApiError` и понять,
       что это ошибка API, а не случайный баг в коде.
   ------------------------------------------------------------------ */
export class ApiError extends Error {
  constructor(status, message, details = null) {
    super(message);            // передаём текст в родительский Error
    this.name = "ApiError";    // имя для отладки и проверок
    this.status = status;      // HTTP-код или 0 для сетевой ошибки
    this.details = details;    // тело ответа, если было
  }
}

/* ------------------------------------------------------------------
   request — универсальная функция запроса к API.

   Принимает:
     path    — путь относительно BASE_URL (например, "/search.json");
     options — объект с полями:
                 params  — объект с query-параметрами (q, limit, ...);
                 signal  — AbortSignal для отмены запроса;
                 ...rest — прочие опции fetch (method, headers, body).

   Возвращает распарсенный JSON или null, если ответ пустой (204).

   Бросает ApiError при:
     - сетевой ошибке (нет интернета, DNS, CORS) → status = 0;
     - HTTP-ошибке (404, 500, ...) → status = код ответа.

   НЕ бросает исключение при отмене — пробрасывает AbortError,
   чтобы вызывающий код мог его отдельно обработать.
   ------------------------------------------------------------------ */
export async function request(path, options = {}) {
  // Деструктуризация: вытаскиваем params и signal, остальное
  // (method, headers, body) попадёт в rest и уйдёт в fetch как есть.
  const { params, signal, ...rest } = options;

  // Собираем полный URL. new URL умеет склеивать базовый адрес
  // с относительным путём корректно, без ручных слэшей.
  const url = new URL(path, BASE_URL);

  // Если переданы query-параметры — добавляем через URLSearchParams.
  // Это требование задания: не конкатенировать строку вручную
  // ("?q=" + query + "&limit=20"), а использовать стандартный класс.
  // URLSearchParams сам экранирует спецсимволы в значениях.
  if (params) {
    url.search = new URLSearchParams(params).toString();
  }

let response;

// Максимум две попытки:
// первая обычная + один автоматический повтор.
for (let attempt = 0; attempt < 2; attempt += 1) {
  try {
    response = await fetch(url, {
      headers: {
        "Accept": "application/json",
        ...(rest.headers || {}),
      },
      signal,
      ...rest,
    });
  } catch (cause) {
    if (cause.name === "AbortError") {
      throw cause;
    }

    throw new ApiError(
      0,
      "Нет соединения с сервером",
      cause
    );
  }

  if (
    response.status >= 500 &&
    response.status < 600 &&
    attempt === 0
  ) {
    await wait(RETRY_DELAY);
    continue;
  }

  break;
}

// Дальше обычная проверка HTTP-ошибки.
if (!response.ok) {
    // Пытаемся прочитать тело ответа (там может быть описание ошибки).
    // Если тело не JSON — вернём null, ничего страшного.
    const body = await response.json().catch(() => null);

    // Бросаем ApiError с кодом ответа и сообщением из тела
    // или стандартным текстом HTTP (например, "Not Found").
    throw new ApiError(
      response.status,
      body?.detail || body?.error || response.statusText || "Ошибка запроса",
      body
    );
  }

  // 204 — ответ без тела. Возвращаем null, чтобы вызывающий код
  // не пытался парсить пустую строку.
  if (response.status === 204) {
    return null;
  }

  // Успешный ответ — парсим JSON и возвращаем данные.
  return response.json();
}