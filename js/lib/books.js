/* ==========================================================================
   lib/books.js — чистые функции работы с книгами.

   ВАЖНО (для защиты): этот модуль НИЧЕГО НЕ ЗНАЕТ О DOM.
   Здесь нет ни document, ни querySelector, ни addEventListener —
   только работа с массивами и объектами. Такое разделение позволяет
   переиспользовать логику где угодно: в браузере, в тестах, в Node.js.

   Второе правило: ни одна функция здесь НЕ МЕНЯЕТ входные данные.
   Мы никогда не вызываем sort() или push() прямо на переданном массиве.
   Вместо этого копируем массив через spread [...books] и работаем с копией.

   Что экспортируется:
     GENRE_LABELS  — словарь жанров для интерфейса (на английском в коде,
                     на русском в подписи select);
     filterBooks   — фильтрация по поисковому запросу, жанру и доступности;
     sortBooks     — сортировка по названию, году или рейтингу;
     countAvailable — сколько книг доступно (для счётчика);
     getBookById   — найти одну книгу по id (пригодится для списка желаемого).
   ========================================================================== */

// Словарь жанров для интерфейса. В данных жанр хранится латиницей
// (scifi, detective и так далее), чтобы не было проблем с кодировкой
// и регистром. А в select показываем русские названия.
export const GENRE_LABELS = {
  roman:      "Роман",
  scifi:      "Фантастика",
  detective:  "Детектив",
  fantasy:    "Фэнтези",
  nonfiction: "Нон-фикшн",
};

/* ------------------------------------------------------------------
   filterBooks — фильтрация массива книг.

   Принимает:
     books    — исходный массив (мы его НЕ меняем);
     filters  — объект с полями query, genre, onlyAvailable.

   Возвращает новый массив отфильтрованных книг.
   Три фильтра работают в комбинации: сначала проверяем жанр,
   потом доступность, потом поиск. Если какой-то фильтр не задан,
   он просто пропускает всё.
   ------------------------------------------------------------------ */
export function filterBooks(books, filters) {
  // Деструктуризация: достаю три поля из объекта filters.
  // Если поле не задано, ставлю значение по умолчанию.
  const { query = "", genre = "all", onlyAvailable = false } = filters;

  // Привожу поисковый запрос к нижнему регистру и обрезаю пробелы.
  // Так поиск будет регистронезависимым: «Тайная» и «тайная» найдут одно и то же.
  const q = query.trim().toLowerCase();

  // filter возвращает НОВЫЙ массив — исходный books не меняется.
  // Это важно: если бы мы работали с исходным массивом, при сбросе фильтров
  // восстанавливать было бы нечего.
  return books.filter((book) => {
    // Фильтр по жанру: если выбран «все» — пропускаем, иначе сравниваем.
    if (genre !== "all" && book.genre !== genre) {
      return false;
    }

    // Фильтр по доступности: если чекбокс включён, оставляем только
    // книги с available === true.
    if (onlyAvailable && !book.available) {
      return false;
    }

    // Фильтр по поиску: если запрос пустой — пропускаем всё.
    if (!q) {
      return true;
    }

    // Ищем совпадение в названии и в авторе. toLowerCase() приводим
    // обе стороны к одному регистру. includes — вхождение подстроки.
    const titleMatch = book.title.toLowerCase().includes(q);
    const authorMatch = book.author.toLowerCase().includes(q);

    // Книга проходит, если совпадение хотя бы в одном из полей.
    return titleMatch || authorMatch;
  });
}

/* ------------------------------------------------------------------
   sortBooks — сортировка массива книг.

   Принимает:
     books — исходный массив (НЕ меняем);
     by    — ключ сортировки: "title" | "year" | "rating".

   Возвращает НОВЫЙ отсортированный массив.
   Ключевой момент: мы копируем массив через [...books], потому что
   метод sort мутирует (меняет) массив, на котором вызван.
   Если не скопировать — исходный порядок книг из data/books.js
   потеряется навсегда.
   ------------------------------------------------------------------ */
export function sortBooks(books, by) {
  // Копируем массив. Теперь sort будет менять копию, а не оригинал.
  const copy = [...books];

  if (by === "year") {
    // Сортировка по году: новые сначала. Значит, по убыванию (b.year - a.year).
    return copy.sort((a, b) => b.year - a.year);
  }

  if (by === "rating") {
    // Сортировка по рейтингу: высокий сначала. Тоже убывание.
    return copy.sort((a, b) => b.rating - a.rating);
  }

  // По умолчанию (и для by === "title") — алфавитный порядок.
  // localeCompare умеет сравнивать строки с учётом языка и регистра.
  // Передаём "ru", чтобы «Ё» сортировалась правильно.
  return copy.sort((a, b) => a.title.localeCompare(b.title, "ru"));
}

/* ------------------------------------------------------------------
   countAvailable — сколько книг доступно.

   Принимает массив, возвращает число.
   Используем filter + length: сначала оставляем только доступные книги,
   потом смотрим, сколько их. Никаких изменений исходного массива.
   ------------------------------------------------------------------ */
export function countAvailable(books) {
  return books.filter((book) => book.available).length;
}

/* ------------------------------------------------------------------
   getBookById — найти книгу по её id.

   Принимает массив и число id, возвращает объект книги или undefined,
   если книги с таким id нет.
   Функция пригодится для списка желаемого: там мы храним только id,
   а при отрисовке нужно найти саму книгу по этому id.
   ------------------------------------------------------------------ */
export function getBookById(books, id) {
  return books.find((book) => book.id === id);
}