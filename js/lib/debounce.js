/* ==========================================================================
   lib/debounce.js — утилита отложенного запуска функции.

   Задача: не запускать функцию на каждое событие, а подождать,
   пока события прекратятся на N миллисекунд. Так поиск не будет
   улетать на каждую букву — только когда пользователь остановился.

   ВАЖНО (для защиты): debounce и throttle — разные вещи.
     debounce: запускает функцию ОДИН раз, когда события прекратились.
     throttle: запускает функцию раз в N мс, независимо от того,
               прекратились события или нет.
   Нам нужен именно debounce: пока пользователь печатает — ждём,
   когда остановится — отправляем один запрос.
   ========================================================================== */

/**
 * Возвращает обёртку над fn, которая откладывает вызов на delay мс.
 * При повторном вызове обёртки таймер перезапускается, а предыдущая
 * запланированная функция не выполняется.
 *
 * Пример:
 *   const search = debounce((q) => console.log(q), 350);
 *   search("h"); search("ha"); search("har");  // ничего не выведет
 *   // через 350 мс после последнего вызова выведет "har"
 */
export function debounce(fn, delay) {
  // Храним id таймера между вызовами обёртки.
  // Замыкание: переменная timer живёт в этой функции и доступна
  // в возвращаемой обёртке. Это классический пример замыкания.
  let timer = null;

  return function debounced(...args) {
    // Если предыдущий таймер ещё не отработал — отменяем его.
    // Именно поэтому промежуточные вызовы не выполняются.
    if (timer !== null) {
      clearTimeout(timer);
    }

    // Ставим новый таймер. Через delay мс он вызовет fn с теми же
    // аргументами, что получил последний вызов обёртки.
    // this сохраняем через .apply, чтобы функция знала контекст.
    timer = setTimeout(() => {
      fn.apply(this, args);
      timer = null;   // после выполнения сбрасываем таймер
    }, delay);
  };
}