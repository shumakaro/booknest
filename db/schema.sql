-- Часть A: нормализованная схема до миграции с преобразованием имён.
CREATE TABLE authors (
 id integer GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
 name varchar(120) NOT NULL UNIQUE,
 birth_year integer CHECK (birth_year BETWEEN 1000 AND 2100),
 CONSTRAINT authors_name_ck CHECK (length(trim(name)) > 0)
);
CREATE TABLE books (
 id integer GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
 title varchar(200) NOT NULL,
 author_id integer NOT NULL REFERENCES authors(id) ON DELETE RESTRICT,
 year integer NOT NULL CONSTRAINT books_year_ck CHECK (year BETWEEN 1450 AND 2100),
 isbn varchar(13) UNIQUE,
 total_copies integer NOT NULL DEFAULT 1 CONSTRAINT books_copies_ck CHECK (total_copies >= 0),
 description text NOT NULL DEFAULT '',
 created_at timestamptz NOT NULL DEFAULT now(),
 CONSTRAINT books_title_ck CHECK (length(trim(title)) > 0),
 CONSTRAINT books_isbn_ck CHECK (isbn IS NULL OR isbn ~ '^[0-9]{13}$')
);
CREATE TABLE genres (
 id integer GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
 code varchar(30) NOT NULL UNIQUE,
 name varchar(100) NOT NULL,
 CONSTRAINT genres_code_ck CHECK (code IN ('scifi','history','poetry','cs','fiction'))
);
-- Удаление связи не удаляет ни книгу, ни жанр; сама связь без них не нужна.
CREATE TABLE book_genres (
 book_id integer REFERENCES books(id) ON DELETE CASCADE,
 genre_id integer REFERENCES genres(id) ON DELETE CASCADE,
 PRIMARY KEY (book_id, genre_id)
);
CREATE TABLE users (
 id integer GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
 email varchar(254) NOT NULL UNIQUE,
 password_hash varchar(255) NOT NULL,
 role varchar(20) NOT NULL DEFAULT 'member',
 is_active boolean NOT NULL DEFAULT true,
 created_at timestamptz NOT NULL DEFAULT now(),
 CONSTRAINT users_role_ck CHECK (role IN ('member','librarian')),
 CONSTRAINT users_email_ck CHECK (position('@' in email) > 1)
);
-- Общий первичный и внешний ключ задаёт связь 1:1.
CREATE TABLE profiles (
 user_id integer PRIMARY KEY REFERENCES users(id) ON DELETE CASCADE,
 full_name text NOT NULL,
 faculty text
);
-- История выдач не должна исчезать вместе с книгой или читателем.
CREATE TABLE loans (
 id integer GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
 book_id integer NOT NULL REFERENCES books(id) ON DELETE RESTRICT,
 user_id integer NOT NULL REFERENCES users(id) ON DELETE RESTRICT,
 issued_at date NOT NULL DEFAULT current_date,
 due_date date NOT NULL,
 returned_at date,
 CONSTRAINT loans_dates_ck CHECK (due_date > issued_at),
 CONSTRAINT loans_return_ck CHECK (returned_at IS NULL OR returned_at >= issued_at)
);
CREATE UNIQUE INDEX loans_active_uniq ON loans(book_id,user_id) WHERE returned_at IS NULL;
CREATE INDEX books_author_year_idx ON books(author_id,year,id);
CREATE INDEX loans_due_idx ON loans(due_date) WHERE returned_at IS NULL;
CREATE INDEX books_search_idx ON books USING gin(to_tsvector('simple',title));
CREATE VIEW overdue_loans AS SELECT * FROM loans WHERE returned_at IS NULL AND due_date < current_date;
